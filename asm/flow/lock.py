"""``pipeline.lock``: the local list of pipeline stages (``.cache/_flow/``).

A stage is a literal ``stagelog.step('<name>', <level>, '<kind>', ...)`` call in
``main/`` or ``lib/``.  The lock records each one, so adding, removing or
re-classifying a stage is a visible diff in review -- the moment to ask "should
this extend an earlier stage instead of repairing it?".

Static rules, checked without running a build:

* the call's name, level and kind are literals (phase stages, built from
  ``PhaseContract`` slots, are exempt: they are not literal);
* ``repair`` / ``recompute`` / ``cleanup`` must give ``repairs=`` and ``why=``;
* the scan matches ``pipeline.lock`` exactly.

Dynamic rule (needs a build's ledgers, ``python3 -m flow.generate --check``): a
``produce`` stage that rewrote another stage's output -- an *undeclared* repair
-- must be listed under ``undeclared`` in the lock, and the list may only
shrink.
"""

import ast
import os

from lib.cachedirs import pipeline_lock_path
from lib.stagelog import DECLARED, KINDS

ASM_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCK_PATH = pipeline_lock_path()
_SCAN = ('main', 'lib')
_SKIP = {'tests', '__pycache__', 'aztec', 'decompile'}

_HEADER = """\
# Pipeline stage lock -- generated by `python3 -m flow.generate --lock`.
# One line per stage: L<level> <kind> <name>.  A diff here means a stage was
# added, removed or re-classified: justify it in review (extend an earlier
# stage, or declare a repair with `repairs=` and `why=`).
# `undeclared <name>` lines are produce stages the ledger caught rewriting
# another stage's output; the list may only shrink.
"""


def _literal(node):
    return node.value if isinstance(node, ast.Constant) else None


def _is_step_call(node):
    func = node.func
    return (isinstance(node, ast.Call) and isinstance(func, ast.Attribute)
            and func.attr == 'step' and isinstance(func.value, ast.Name)
            and func.value.id == 'stagelog')


def scan(root=ASM_DIR):
    """``([(level, kind, name)], [problem, ...])`` from the source tree."""
    stages, problems = [], []
    for top in _SCAN:
        for folder, dirs, files in os.walk(os.path.join(root, top)):
            dirs[:] = sorted(d for d in dirs if d not in _SKIP)
            for filename in sorted(files):
                if not filename.endswith('.py'):
                    continue
                path = os.path.join(folder, filename)
                with open(path, encoding='utf-8') as f:
                    tree = ast.parse(f.read(), path)
                for node in ast.walk(tree):
                    if not (isinstance(node, ast.Call) and _is_step_call(node)):
                        continue
                    where = f'{os.path.relpath(path, root)}:{node.lineno}'
                    args = node.args
                    name = _literal(args[0]) if args else None
                    if not isinstance(name, str):
                        continue  # f-string phase stage: governed by PhaseContract
                    level = _literal(args[1]) if len(args) > 1 else None
                    kind = (_literal(args[2]) if len(args) > 2 else
                            next((_literal(k.value) for k in node.keywords
                                  if k.arg == 'kind'), 'produce'))
                    if not isinstance(level, int) or kind not in KINDS:
                        problems.append(f'{where}: {name!r} needs a literal int '
                                        f'level and a known kind')
                        continue
                    given = {k.arg for k in node.keywords}
                    if kind in DECLARED and not {'repairs', 'why'} <= given:
                        problems.append(f'{where}: {kind} stage {name!r} needs '
                                        f'repairs= and why=')
                    stages.append((level, kind, name))
    return sorted(set(stages), key=lambda s: (s[0], s[2])), problems


def read(path=LOCK_PATH):
    """``(stages, undeclared)`` from the lock file."""
    stages, undeclared = [], []
    if not os.path.exists(path):
        return stages, undeclared
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = line.split()
            if parts[0] == 'undeclared':
                undeclared.append(parts[1])
            else:
                stages.append((int(parts[0][1:]), parts[1], parts[2]))
    return sorted(stages, key=lambda s: (s[0], s[2])), sorted(undeclared)


def write(stages, undeclared, path=LOCK_PATH):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(_HEADER)
        for level, kind, name in stages:
            f.write(f'L{level} {kind} {name}\n')
        for name in sorted(undeclared):
            f.write(f'undeclared {name}\n')


def diff(found, locked):
    """Human-readable differences between two stage lists."""
    found, locked = set(found), set(locked)
    out = [f'+ L{l} {k} {n}  (new stage)' for l, k, n in sorted(found - locked)]
    out += [f'- L{l} {k} {n}  (stage gone or re-classified)'
            for l, k, n in sorted(locked - found)]
    return out
