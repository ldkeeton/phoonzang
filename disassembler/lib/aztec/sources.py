"""Catalog of the Manx Aztec C86 v4.2b runtime sources.

The game was built with Aztec C86 v4.2b: its runtime is that release's
small-model ``C.LIB``, every member of which :mod:`.libcheck` rebuilds
byte-exact from these sources.  ``make init`` unpacks the release's
``ARC/*.ARC`` bundles into ``dos_compilers/aztec_src/v42b/<archive>/<file>``.

Sources are keyed by lower-case base name.  Names repeat across archives
(``croot.c`` is in both ``cpm86`` and ``dos20``); the directories the DOS
library is built from (``build/c.bld``) win.
"""

import os
import re
import shutil

from ..autogen import MARKER_ASM, is_generated, stamp
from ..cachedirs import prebuild_dir, src_dir

_ASM_DIR = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))
_DOSCOMP = os.path.join(_ASM_DIR, 'dos_compilers')
_MASTER = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       'lmacros_master.h')

#: Generated by the renderer into ``include/``; not a vendor header.
HOST_SYMBOLS_INC = 'host_symbols.inc'
#: The renderer's record layouts (``lib.record_layout.STRUCTS_INC``).
STRUCTS_INC = 'structs.inc'

#: The one Aztec release the game was built with (lib.aztec.compile.VERSION).
VERSION = 'v42b'

VERSIONS = {
    VERSION: os.path.join(_DOSCOMP, 'Manx Aztec C86 v42b'),
}

# Per-version include roots (headers that go with the source).
INCLUDE_DIRS = {
    VERSION: os.path.join(VERSIONS[VERSION], 'INCLUDE'),
}

_CACHE = {}


def src_root(version):
    """``dos_compilers/aztec_src/<version>``: the sources ``make init``
    unpacks from the release's ``ARC/*.ARC``, one dir per archive."""
    return os.path.join(_DOSCOMP, 'aztec_src', version)


def version_root(version):
    try:
        return VERSIONS[version]
    except KeyError:
        raise ValueError(f'unknown Aztec source version {version!r}')


def include_dir(version):
    return INCLUDE_DIRS.get(version)


def staged_include_dir(project, version=VERSION):
    """The vendor include tree staged for *project* by ``make prebuild``."""
    return os.path.join(prebuild_dir(project), 'include', version)


def project_include_dir(project, out_dir=None):
    """The self-contained include tree the build compiles against."""
    return os.path.join(out_dir or src_dir(project), 'include')


def stage_headers(project, version=VERSION):
    """Copy *version*'s vendor include tree into *project*'s prebuild cache.

    Names are lower-cased: DOS resolves them case-insensitively, and the
    generated ``src_<project>/include`` uses the same names.  The build copies
    them into the project tree before compiling; ``make prebuild`` re-stages.
    """
    dest = staged_include_dir(project, version)
    if os.path.isfile(os.path.join(dest, 'lmacros.h')):
        return
    root = include_dir(version)
    if not root or not os.path.isdir(root):
        return
    os.makedirs(dest, exist_ok=True)
    for name in os.listdir(root):
        src = os.path.join(root, name)
        if os.path.isfile(src):
            shutil.copyfile(src, os.path.join(dest, name.lower()))


def master_text():
    """The high-level macro fragment appended to the vendor ``LMACROS.H``."""
    with open(_MASTER, errors='replace') as f:
        return f.read()


def merged_lmacros(project, version=VERSION):
    """The staged vendor ``lmacros.h`` with the high-level macros appended."""
    with open(os.path.join(staged_include_dir(project, version),
                           'lmacros.h'), errors='replace') as f:
        base = f.read()
    if not base.endswith('\n'):
        base += '\n'
    return base + '\n' + master_text()


def header_files(project, versions=None):
    """``{lower-case name: text}`` of the staged headers, lmacros merged."""
    out = {}
    for version in (versions or VERSIONS):
        root = staged_include_dir(project, version)
        if not os.path.isdir(root):
            continue
        for name in sorted(os.listdir(root)):
            path = os.path.join(root, name)
            if not os.path.isfile(path):
                continue
            key = name.lower()
            with open(path, errors='replace') as f:
                out[key] = f.read()
            if key == 'lmacros.h':
                out[key] = merged_lmacros(project, version)
    return out


def _clean_text(text):
    """Drop trailing whitespace and leave exactly one final newline."""
    lines = [line.rstrip() for line in text.splitlines()]
    while lines and not lines[-1]:
        lines.pop()
    return '\n'.join(lines) + ('\n' if lines else '')


def install_headers(project, out_dir, versions=None):
    """Copy the staged headers into ``src_<project>/include``.

    This is the build's self-contained header tree: the compile mounts it as
    INCLUDE and never sees the prebuild staging (or ``dos_compilers``).  Stale
    generated headers are removed; hand-owned files and the renderer's
    ``host_symbols.inc`` and ``structs.inc`` are left alone.
    """
    files = header_files(project, versions)
    if not files:
        raise FileNotFoundError(
            f'{project}: headers are not staged; run "make prebuild {project}"')
    dest = project_include_dir(project, out_dir)
    os.makedirs(dest, exist_ok=True)
    for name, text in files.items():
        path = os.path.join(dest, name)
        # lmacros.h is included by the assembler, whose comment is ``;``.
        marker = MARKER_ASM if name == 'lmacros.h' else None
        data = stamp(_clean_text(text), path, marker)
        try:
            with open(path, errors='replace') as f:
                if f.read() == data:
                    continue
        except OSError:
            pass
        with open(path, 'w') as f:
            f.write(data)
    keep = set(files) | {HOST_SYMBOLS_INC, STRUCTS_INC}
    for name in os.listdir(dest):
        path = os.path.join(dest, name)
        if name in keep or not os.path.isfile(path):
            continue
        if is_generated(path):
            os.unlink(path)


def library_dirs(version):
    """The archive directories ``C.LIB`` is built from, in ``c.bld`` order."""
    path = os.path.join(src_root(version), 'build', 'c.bld')
    try:
        with open(path, errors='replace') as f:
            names = f.read().split()
    except OSError:
        return []
    return list(dict.fromkeys(n.split('/')[0] for n in names if '/' in n))


def catalog(version):
    """Return ``{lower-case filename: source text}`` for *version*.

    Every unpacked archive contributes; on a name clash the ``C.LIB``
    directories win over the others (CP/M, math, screen, graphics).
    """
    if version in _CACHE:
        return _CACHE[version]
    root = src_root(version)
    if not os.path.isdir(root):
        raise FileNotFoundError(f'{root} missing; run "make init"')
    preferred = library_dirs(version)
    dirs = sorted(d for d in os.listdir(root)
                  if os.path.isdir(os.path.join(root, d)))
    order = [d for d in dirs if d not in preferred] + \
            [d for d in preferred if d in dirs]
    out = {}
    for d in order:
        for fn in sorted(os.listdir(os.path.join(root, d))):
            if fn.endswith(('.c', '.asm')):
                with open(os.path.join(root, d, fn), errors='replace') as f:
                    out[fn] = f.read()
    _CACHE[version] = out
    return out


def source_dir(version, filename):
    """The archive directory ``catalog`` takes *filename* from, or None."""
    root = src_root(version)
    preferred = library_dirs(version)
    dirs = sorted(d for d in os.listdir(root)
                  if os.path.isdir(os.path.join(root, d)))
    order = [d for d in dirs if d not in preferred] + \
            [d for d in preferred if d in dirs]
    found = None
    for d in order:
        if os.path.isfile(os.path.join(root, d, filename)):
            found = d
    return found


class PatchError(ValueError):
    """A sidecar ``vendor_patches`` edit does not apply to its source."""


def apply_edits(text, edits, where='vendor patch'):
    """Return *text* with each ``{"find", "replace"}`` edit applied in order.

    A ``find`` must occur exactly once: the edits record how the game's copy
    of a library routine differs from the vendor source, so one that no longer
    applies (or applies twice) is an error rather than a silent no-op.
    """
    for index, edit in enumerate(edits):
        find, replace = edit['find'], edit['replace']
        count = text.count(find)
        if count != 1:
            raise PatchError(f'{where}: edit {index} {find!r} occurs {count} '
                             f'times (expected once)')
        text = text.replace(find, replace)
    return text


_DEF_CACHE = {}


def _key(name):
    """Index key for a C name (:func:`lib.aztec.compile.symbol_key`)."""
    from .compile import symbol_key
    return symbol_key(name)


def _asm_key(name):
    """Index key for an assembler ``public``/``proc`` name (``ovloader_``)."""
    from .compile import aztec_name
    return _key(aztec_name(name))


_KEYWORDS = {
    'if', 'for', 'while', 'switch', 'return', 'sizeof', 'do', 'else',
}

# A definition sits at column zero and ends with ``name(...)``.  Optional
# return-type tokens may precede the name (``int lseek(``); K&R sources often
# put the type on the previous line, leaving ``name(...)`` alone.
_DEF_RE = re.compile(
    r'^(?:[A-Za-z_][A-Za-z0-9_]*[ \t\*]+)*'
    r'([A-Za-z_][A-Za-z0-9_]*)[ \t]*\(', re.M)


def _definition_files(version):
    """Index of function definitions: normalized name -> [filenames]."""
    if version in _DEF_CACHE:
        return _DEF_CACHE[version]
    index = {}
    for fn, text in catalog(version).items():
        if not fn.endswith('.c'):
            continue
        for m in _DEF_RE.finditer(text):
            name = _key(m.group(1))
            if name in _KEYWORDS or not name:
                continue
            index.setdefault(name, [])
            if fn not in index[name]:
                index[name].append(fn)
        # ``#asm`` blocks define routines too (``ovloader_ proc near``).
        for m in _ASM_PROC_RE.finditer(text):
            name = _asm_key(m.group(1))
            if name and fn not in index.setdefault(name, []):
                index[name].append(fn)
    _DEF_CACHE[version] = index
    return index


def definition_files(version, name):
    """Files in *version* whose text defines *name* at column zero."""
    return list(_definition_files(version).get(_key(name), []))


_ASM_DEF_CACHE = {}

# An assembly routine is introduced by the library macro ``procdef name`` or,
# in the hand-written modules, ``public a, b`` / ``name proc``.  Runtime-private
# names carry a ``$`` (``$csav``, ``$begin``) and C names an ``_``/``_`` affix.
# ``public`` alone also covers forward references, so this over-approximates;
# the mux's exact byte compare is what decides a real match.
_ASM_DECL_RE = re.compile(
    r'^[ \t]*(?:procdef|proc|entry|public|intrdef)[ \t]+([^;\n]+)', re.M | re.I)
_ASM_PROC_RE = re.compile(r'^[ \t]*([A-Za-z0-9_$@?]+)[ \t]+proc\b', re.M | re.I)
_ASM_NAME_RE = re.compile(r'[A-Za-z0-9_$@?]+')


def _asm_names(text):
    """Index keys of the names *text* defines.

    ``procdef`` takes the C name (it appends the ``_`` itself); ``public`` and
    ``proc`` spell it as the assembler does (``__tty_rd_``).
    """
    for m in _ASM_DECL_RE.finditer(text):
        # ``procdef strcmp,<<str1,ptr>,...>``: only the first name is defined.
        decl = m.group(0).split(None, 1)
        if decl[0].lower() == 'procdef':
            first = _ASM_NAME_RE.match(m.group(1).strip())
            if first:
                yield _key(first.group(0))
        else:
            yield from map(_asm_key, _ASM_NAME_RE.findall(m.group(1)))
    for m in _ASM_PROC_RE.finditer(text):
        yield _asm_key(m.group(1))


def _asm_definition_files(version):
    if version in _ASM_DEF_CACHE:
        return _ASM_DEF_CACHE[version]
    index = {}
    for fn, text in catalog(version).items():
        if not fn.endswith('.asm'):
            continue
        for name in _asm_names(text):
            if not name:
                continue
            index.setdefault(name, [])
            if fn not in index[name]:
                index[name].append(fn)
    _ASM_DEF_CACHE[version] = index
    return index


def asm_definition_files(version, name):
    """Hand-written ``.asm`` files in *version* that define *name*."""
    return list(_asm_definition_files(version).get(_key(name), []))
