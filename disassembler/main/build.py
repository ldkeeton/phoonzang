def check_build_sidecar_use(project, bins):
    """Fail on a build-wide sidecar entry no binary applied.

    One ``routines``/``api_dispatch`` entry names code in every binary that
    carries it, a ``vendor_patches`` entry a library routine, a
    ``compiler_flags`` prefix the C routines it covers; each must have done
    so somewhere.  Every ``binaries`` entry must name a binary of the app.
    """
    sidecar = load_sidecar(project) or {}
    used = collect_sidecar_use(labels_dir(project), bins)
    problems = []
    for key in ('routines', 'api_dispatch', 'vendor_patches'):
        for entry in sidecar.get(key) or {}:
            if entry not in used.get(key, ()):
                problems.append(f'{key}[{entry}]: no binary has it')
    prefixes = (sidecar.get('compiler_flags') or {}).get('prefixes', {})
    for prefix in prefixes:
        if prefix not in used.get('compiler_flags', ()):
            problems.append(f'compiler_flags.prefixes[{prefix}]: no C routine '
                            f'takes it')
    for name in (sidecar.get('binaries') or {}):
        if name not in bins:
            problems.append(f'binaries.{name}: no such binary')
    if problems:
        raise SidecarError(
            f'{len(problems)} sidecar entr{"y" if len(problems) == 1 else "ies"} '
            f'not applied:\n  ' + '\n  '.join(problems))


def _slot_drivers(project):
    """The binaries some binary's ``driver_slots`` calls the API of."""
    sidecar = load_sidecar(project) or {}
    return {slots['driver']
            for info in (sidecar.get('binaries') or {}).values()
            for slots in info.get('driver_slots') or ()}


def aggregate_host_data(project, consumers):
    """Merge the *consumers*' exported DS refs into the host's union (D7.1).

    Returns the path of the written union, or ``None`` when nothing references
    host data.  Two consumers that disagree on a name are a
    :class:`~lib.link.LinkError`.
    """
    union = collect_host_data(labels_dir(project), consumers)
    if not union:
        return None
    return write_host_data_offsets(project, union)


def foreign_args(project, name, cross_refs):
    """The source-label flags for one consumer, or ``None`` when it has none.

    The labels file is the source's export from this build; the consumer
    fails if it is missing rather than run without it.
    """
    if name not in cross_refs:
        return None
    prefix = next(iter({src for _, src in cross_refs[name]}), '')
    json_path = os.path.join(labels_dir(project), f'{prefix}_labels.json')
    return [f'--foreign-labels={json_path}', f'--foreign-prefix={prefix}']


def _patches_for(out_dir, name):
    """The per-binary ``byte_patches`` entries for *out_dir*'s project."""
    base = os.path.basename(os.path.normpath(out_dir))
    project = base[len('src_'):] if base.startswith('src_') else base
    sidecar = load_sidecar(project) if project else None
    return ((sidecar_per_binary(sidecar, name) if sidecar else {})
            .get('byte_patches') or ())


def nasm_binary(out_dir, name, rel_path, patches=None):
    """Assemble one binary with NASM; return its exit status.

    After a successful assembly, each ``byte_patches`` entry writes its
    ``apply`` bytes into ``build_out``.  The source keeps the compiler's
    (``natural``) bytes, so a byte-exact C routine can gate and verify; only
    the shipped artifact gets the post-link edit.
    """
    asm_path = os.path.join(out_dir, f'{name}.asm')
    bin_path = os.path.join(out_dir, 'build_out', rel_path)
    os.makedirs(os.path.dirname(bin_path), exist_ok=True)
    r = childproc.run(
        ['nasm', '-O0', '-f', 'bin', '-w-number-overflow', '-w-other',
         *include_args(out_dir), '-o', bin_path, asm_path],
        capture_output=True, text=True,
    )
    if r.returncode != 0:
        print(f'  BUILD FAIL: {name}.asm -> {rel_path}')
        for line in r.stderr.strip().split('\n'):
            print(f'    {line}')
        return r.returncode

    if patches is None:
        patches = _patches_for(out_dir, name)
    if patches:
        try:
            with open(bin_path, 'rb') as f:
                data = f.read()

            def applied(patch, before):
                progress.log(f'  patch {name}: 0x{patch["offset"]:04x} '
                             f'{before.hex()} -> {patch["apply"].hex()} '
                             f'({patch["note"]})')

            patched = finalize_patches(data, patches, on_apply=applied)
            if patched != data:
                with open(bin_path, 'wb') as f:
                    f.write(patched)
        except PatchError as exc:
            print(f'  BUILD FAIL: {name}.asm -> {rel_path}: {exc}')
            return 1
    return 0


def _batch(batch, items):
    """Run *items* through *batch*; return the failed names, sorted."""
    return sorted(set(batch(items) or ()))


def _generate(run_batch, items, emitted):
    """:func:`_batch` for a *run_batch*, keeping its emitted files in *emitted*."""
    failed, files = run_batch(items)
    emitted.update(files)
    return sorted(set(failed or ()))


def merge_files(emitted):
    """One tree's ``{relative path: text}`` from each binary's emitted files.

    Binaries lay out some files alike (``inc/structs/structs.inc``, a vendor
    header): one copy is kept.  Two binaries writing one path differently is
    an error, not a file one of them silently loses.
    """
    files, owner = {}, {}
    for name in sorted(emitted):
        for rel, text in emitted[name].items():
            if rel in files and files[rel] != text:
                raise LinkError(f'{rel}: {owner[rel]} and {name} lay it out '
                                f'differently')
            files[rel], owner[rel] = text, owner.get(rel, name)
    return files


def _restamp_export(path):
    """A previous build's export data, for its writer to re-stamp.

    Returns the data, or ``None`` when there is no usable export.
    """
    try:
        with open(path) as f:
            record = json.load(f)
    except (OSError, ValueError):
        return None
    data = (record.get('data')
            if isinstance(record, dict) and 'run' in record else record)
    return data or None


def _host_partial_args(project):
    """The last full build's host unions, for a partial build of the host.

    The union of the overlays' host-data references and the family's DS starts
    are whole-project decisions a partial build does not make.  The previous
    full build's files still say what they said when nothing else changed;
    re-stamp them for this build and hand them to the host, so it emits the
    same names it did then.
    """
    from lib.link import (DS_STARTS_NAME, HOST_DATA_OFFSETS_NAME,
                          write_ds_starts, write_host_data_offsets)
    path = os.path.join(labels_dir(project), HOST_DATA_OFFSETS_NAME)
    data = _restamp_export(path)
    if not data:
        return []
    write_host_data_offsets(project, data)
    args = [f'--host-data-offsets={path}']
    path = os.path.join(labels_dir(project), DS_STARTS_NAME)
    data = _restamp_export(path)
    if data:
        write_ds_starts(project, data)
        args.append(f'--ds-starts={path}')
    path = _records_path(project)
    data = _restamp_export(path)
    if data is not None:
        from lib.record_layout import write_layouts
        write_layouts(project, data)
        args.append(f'--records={path}')
    return args


def _records_path(project):
    from lib.record_layout import RECORDS_NAME
    return os.path.join(labels_dir(project), RECORDS_NAME)


def _record_configs(project, host):
    """``(names, configs)``: the host's data names by offset, and the
    sidecar ``record`` of each host ``data_names`` entry that has one."""
    names = {off: str(sym) for off, sym in read_label_json(
        os.path.join(labels_dir(project), f'{host}_datanames.json')).items()}
    entry = ((load_sidecar(project) or {}).get('binaries') or {}).get(host) or {}
    configs = {int(key, 16): info['record']
               for key, info in (entry.get('data_names') or {}).items()
               if isinstance(info, dict) and 'record' in info}
    return names, configs


def _family_starts(project, host, family):
    """The family's ``ds_starts`` union, less the field addresses inside a
    counted sidecar record: the second pass spells those as the record's
    fields (``lib.record_layout.absorb_symbols``)."""
    from lib import record_layout
    union = collect_ds_starts(labels_dir(project), family)
    names, configs = _record_configs(project, host)
    return set(union) - record_layout.absorbed_starts(union, configs,
                                                      keep=names)


def _write_record_layouts(project, host, family, starts_path, report):
    """Unite the family's record accesses into one layout per object.

    The objects are the family's ``ds_starts`` union and the host's data
    names; the sidecar's ``record`` on a host ``data_names`` entry names a
    layout and its fields.  Returns how many layouts were written.
    """
    from lib import record_layout
    names, configs = _record_configs(project, host)
    layouts, notes = record_layout.merge(
        record_layout.collect(labels_dir(project), family),
        set(read_ds_starts(starts_path)) | set(names), names, configs)
    record_layout.write_layouts(project, layouts)
    progress.log(f'{project} | records: {len(layouts)} layout(s)')
    for line in notes:
        report(f'  records: {line}')
    return len(layouts)


def _sync(out_dir, files, report, scopes=None, shared=None, source_moves=None):
    """Bring *out_dir* to this build's *files*: the tree is left alone until
    the layout is final, then only what changed is written or removed.  A
    partial build prunes only its own *scopes*."""
    # A generated prebuild seed may have the same output path as a preserved,
    # hand-owned C/S review source.  Keep the seed in the logical file set
    # through sharing, then avoid replacing that hand-owned file on disk.
    moves = companion_moves(out_dir, shared or {}) if source_moves else []
    moved = {dest for source, dest in moves}
    files = {rel: text for rel, text in files.items()
             if rel not in moved
             if not (rel.endswith(('.c', '.s'))
                     and hand_owned(os.path.join(out_dir, rel)))}
    check_companions(out_dir, files, scopes=scopes, moves=moves)
    written, unchanged, removed = sync(out_dir, files, scopes,
                                       skip=('build_out',))
    if moves:
        source_moves(out_dir, moves)
    report(f'  {os.path.basename(out_dir)}: {written} written, '
           f'{unchanged} unchanged, {removed} removed')


def build_project(project, run_batch, nasm_batch, *, only=None, report=print,
                  overlap=False, source_moves=None):
    """Run the whole project build, recording its level-0 stage ledger.

    *overlap* says two *run_batch* calls may run at once (one worker process
    per binary), so the consumers that need nothing from the others start
    alongside the sources.
    """
    ledger = stagelog.begin(f'{project}/<project>')
    previous_run = begin_run()
    try:
        with write_once():
            failed = _build_project(project, run_batch, nasm_batch,
                                    only=only, report=report,
                                    overlap=overlap, source_moves=source_moves)
    finally:
        end_run(previous_run)
        from lib.cachedirs import stages_dir
        stagelog.end(ledger, os.path.join(stages_dir(project),
                                          f'{project}__project.jsonl'))

    return failed


def _build_project(project, run_batch, nasm_batch, *, only=None, report=print,
                   overlap=False, source_moves=None):
    """Generate *project*; return the names that failed (empty on success).

    *run_batch(items)* takes ``(name, extra_args)`` pairs, generates each binary
    and returns the failed names; *nasm_batch(items)* takes ``(name, rel_path)``
    pairs and assembles them, likewise.  *only* limits the build to one binary
    plus the sources it references, and stops before the whole-project steps.
    """
    app_dir = os.path.join(APPS_DIR, project)
    out_dir = src_dir(project, PROJECT_ROOT)
    os.makedirs(out_dir, exist_ok=True)
    # Both headers bind names from packed data and sidecar bases.  ASM gets
    # the full catalog; C gets proven code uses plus hand-written C uses.
    # Install them once before workers compile or render; no ASM rescan.
    from lib import msgids
    from .messages import collect_message_ids
    used_ids = collect_message_ids(project)
    headers, header_stats = msgids.generate_project(
        project, PROJECT_ROOT, used_ids=used_ids)

    # Install the self-contained header tree before any worker compiles.
    from lib.aztec import sources
    sources.install_headers(project, out_dir)

    bins = discover_binaries(app_dir)
    if not bins:
        report(f'{project}: no binaries found')
        return []
    if only is not None and only not in bins:
        report(f'Unknown binary "{only}" in {project}')
        report(f'Known: {", ".join(sorted(bins))}')
        return [only]

    report(f'\n=== {project} ({len(bins)} binaries) ===')

    emitted = {}    # {binary: its files}, written once the layout is final
    source_failed = set()
    generate_batch = run_batch

    def run_batch(items):
        failed, files = generate_batch(items)
        # A source check can fail after exporting usable labels and ASM.
        # Continue the dependent passes so their surrounding sources emit too.
        source_failed.update(name for name in failed if name in files)
        return [name for name in failed if name not in files], files

    progress.log(f'{project} | detecting cross-references')
    cross_refs = detect_cross_refs(app_dir, bins)
    progress.log(f'{project} | cross-references: {len(cross_refs)} consumer(s)')
    stagelog.step('project.cross_refs', 0, metrics={'consumers': len(cross_refs)})
    source_names = {src for refs in cross_refs.values() for _, src in refs}

    host = host_name(bins)
    # The binaries that share the host's data segment: the indexed-binding
    # union (``ds_starts``) is drawn from and handed to these only.
    family = {host} | {n for n, refs in cross_refs.items()
                       if any(src == host for _, src in refs)}

    # 0. a driver a program calls through ``driver_slots`` runs before
    #    everything: the program's thunks read through the arguments the
    #    driver's handlers do (its pointer-parameter export), and the host's
    #    are handed on to the overlays in step 1.
    drivers = sorted(_slot_drivers(project) & set(bins))
    # a consumer outside the host family that takes no source labels needs
    # nothing from the passes below: it runs alongside them, and only the
    # host's DS union (step 4) waits for it.
    early = []
    if overlap and only is None:
        early = [n for n in sorted(bins) if n not in source_names
                 and n not in family and n not in cross_refs
                 and n not in drivers]
    completed = False
    pool = early_run = None
    early_emitted = {}
    if early:
        progress.log(f'{project} | independent consumers: {len(early)} '
                     f'binary(ies), started now')
        pool = ThreadPoolExecutor(max_workers=1)
        early_run = pool.submit(_generate, run_batch,
                                [(n, None) for n in early], early_emitted)
    try:
        if drivers:
            progress.log(f'{project} | drivers: {len(drivers)} binary(ies)')
            failed = _generate(run_batch, [
                (n, foreign_args(project, n, cross_refs)) for n in drivers],
                emitted)
            if failed:
                report(f'{project}: driver(s) failed: '
                       f'{", ".join(sorted(set(failed)))}')
                return failed

        # 1. the sources, so each consumer below can be handed their labels
        needed = source_names
        if only is not None:
            needed = ({src for _, src in cross_refs.get(only, [])}
                      | ({only} if only in source_names else set()))
        # The host is emitted once, in step 4; a partial build never reaches it,
        # so it takes the last full build's whole-project unions instead.
        host_partial = (_host_partial_args(project)
                        if only == host else [])
        items = [(name, ['--export-labels']
                  + (['--labels-only'] if name == host and only != host else [])
                  + (host_partial if name == host else []))
                 for name in sorted(source_names & set(bins) & needed)]
        progress.log(f'{project} | export sources: {len(items)} binary(ies)')
        failed = _generate(run_batch, items, emitted)
        stagelog.step('project.export_sources', 0, metrics={'sources': len(items)})
        if failed:
            report(f'{project}: source binary(ies) failed: '
                   f'{", ".join(sorted(set(failed)))}')
            return failed

        # 3. the consumers
        consumers = [n for n in sorted(bins)
                     if n not in source_names and n not in drivers]
        targets = consumers
        if only is not None:
            targets = [only] if only in targets else []
        starts = None
        if any(n in family for n in targets):
            # 3a. a labels-only pass exports the DS starts each family binary
            #     names absolutely; their union lets every one of them bind an
            #     indexed operand to an object another binary names.  The union
            #     needs the whole family, even for one binary's partial build.
            first = [n for n in consumers if n in family]
            progress.log(f'{project} | ds_starts pass: {len(first)} family binary(ies)')
            failed = _generate(run_batch, [
                (n, (foreign_args(project, n, cross_refs) or []) + ['--labels-only'])
                for n in first], emitted)
            if failed:
                report(f'{project}: ds_starts pass failed: '
                       f'{", ".join(sorted(set(failed)))}')
                return failed
            starts = write_ds_starts(project, _family_starts(
                project, host, family))
            progress.log(f'{project} | ds_starts: {len(read_ds_starts(starts))} start(s)')
            stagelog.step('project.ds_starts', 0, metrics={'starts': len(
                read_ds_starts(starts))},
                why='an indexed operand binds only to an object some binary of the '
                    'host family names; the union exists after every one has run')
            layouts = _write_record_layouts(project, host, family, starts,
                                            report)
            stagelog.step('project.records', 0, metrics={'layouts': layouts},
                why='a record layout is one per object across the family, so '
                    'shared fragments spell its fields alike')

        def consumer_flags(n):
            flags = foreign_args(project, n, cross_refs)
            if n in family and starts:
                flags = (flags or []) + [f'--ds-starts={starts}',
                                         f'--records={_records_path(project)}']
            return flags

        progress.log(f'{project} | generating consumers: {len(targets)}')
        failed = _generate(run_batch, [(n, consumer_flags(n)) for n in targets
                                       if n not in early], emitted)
        if early_run is not None:
            progress.log(f'{project} | waiting for {len(early)} independent '
                         f'consumer(s)')
            failed = sorted(set(failed) | set(early_run.result()))
            emitted.update(early_emitted)
        if failed:
            report(f'{project}: asm generation failed: '
                   f'{", ".join(sorted(set(failed)))}')
            report(f'{project}: skipping assembly because ASM generation failed')
            return failed

        stagelog.step('project.consumers', 0, metrics={'consumers': len(targets)})

        if only is not None and source_failed:
            return sorted(source_failed)

        if only is not None:
            # Sharing is a whole-tree decision: the binary's routines go back to
            # the shared files its master included last full build, where its
            # new copies still match them (:func:`reshare_partial`).
            progress.log(f'{project} | syncing partial build: {only}')
            files, shared, diverged = reshare_partial(merge_files(emitted),
                                                      out_dir)
            files.update(headers)
            if shared:
                report(f'  Shared: {sum(len(v) for v in shared.values())} '
                       f'fragments -> {len(shared)} files in shared/')
            for name, rel in diverged:
                report(f'  {name}: its copy differs from {rel}; kept its '
                       f'own until a full build re-decides')
            # Assembling it alone must not leave the others' stale artifacts
            # in build_out, so only this binary's scope is pruned.
            _sync(out_dir, files, report, scopes=[f'{only}.asm', only],
                  shared=shared, source_moves=source_moves)
            completed = True
            progress.log(f'{project} | copying assets for {only}')
            copy_assets(app_dir, os.path.join(out_dir, 'build_out'),
                        {bins[only][0]})
            progress.log(f'{project} | assembling {only}')
            return _batch(nasm_batch, [(only, bins[only][0])])

        # A generation failure without output prevents dependent passes.
        if failed:
            report(f'{project}: skipping assembly because ASM generation failed')
            return failed

        # 4. the host declares the union of the DS offsets its consumers reference
        progress.log(f'{project} | aggregating host data from {len(targets)} consumer(s)')
        offsets = aggregate_host_data(project, targets + drivers)
        if host in source_names:
            progress.log(f'{project} | host emit: {host}')
            flags = ['--export-labels']
            if offsets:
                flags.append(f'--host-data-offsets={offsets}')
            if starts:
                flags.append(f'--ds-starts={starts}')
                flags.append(f'--records={_records_path(project)}')
            failed = _generate(run_batch, [(host, flags)], emitted)
            if failed:
                report(f'{project}: generating {host} with the DS union failed')
                return failed
            stagelog.step('project.host_emit', 0, 'recompute', repairs='project.export_sources',
                why='the host\'s labels come first, its source waits for the overlay DS union')

        if source_failed:
            report(f'{project}: source checks failed; writing inspection output')
            return sorted(source_failed)

        check_build_sidecar_use(project, bins)
        stagelog.step('project.sidecar_use', 0, 'measure',
            why='a build-wide sidecar entry is applied by some binary or is stale')

        # 5. one copy of every routine binaries share (names aside), in shared/
        progress.log(f'{project} | sharing identical routines')
        files, shared = share_files(merge_files(emitted), out_dir,
                                    project_tables(project))
        if shared:
            report(f'  Shared: {sum(len(v) for v in shared.values())} '
                   f'fragments -> {len(shared)} files in shared/')
        stagelog.step('project.share_identical', 0, 'repair', repairs='project.consumers',
            why='fragments of different binaries alike but for names collapse into shared/',
            metrics={'shared_files': len(shared or {}),
                     'fragments': sum(len(v) for v in (shared or {}).values())})

        # 5b. structure report: objects glued onto a routine's file (plan.md §7)
        from lib.compare.cotenancy import scan as scan_cotenancy, summarize
        progress.log(f'{project} | scanning cotenancy')
        cotenancy = scan_cotenancy(out_dir, files=files)
        #report('  ' + summarize(cotenancy))
        stagelog.step('project.cotenancy', 0, 'measure',
            metrics={k: cotenancy[k] for k in ('files', 'glued_files', 'co_tenants',
                                                'code', 'data')})

        progress.log(f'{project} | syncing {len(files)} generated file(s)')
        # The headers are build outputs too; keep them through synchronization.
        files.update(headers)
        _sync(out_dir, files, report, shared=shared, source_moves=source_moves)
        completed = True
        progress.log(f'{project} | copying assets')
        copy_assets(app_dir, os.path.join(out_dir, 'build_out'),
                    {rel for rel, _s in bins.values()})

        # 6. assemble
        progress.log(f'{project} | assembling {len(bins)} binary(ies)')
        stagelog.step('project.assemble', 0)
        return _batch(nasm_batch, [(name, rel) for name, (rel, _s)
                                   in sorted(bins.items())])
    finally:
        if pool is not None:
            pool.shutdown(wait=True)
            emitted.update(early_emitted)
        if not completed and emitted:
            # Keep inspectable output even after failure; partial trees must
            # never prune files belonging to a binary that did not emit.
            files, _, _ = reshare_partial(merge_files(emitted), out_dir)
            files.update(headers)
            files = {rel: text for rel, text in files.items()
                     if not hand_owned(os.path.join(out_dir, rel))}
            written, unchanged, _ = sync(out_dir, files, scopes=[])
            report(f'  Failure output: {written} written, '
                   f'{unchanged} unchanged; no files removed')


def _worker_kwargs(flags):
    """``runner.process`` keywords for a worker's CLI flags."""
    kwargs = {}
    for flag in flags or ():
        key, _, value = flag.partition('=')
        if key == '--export-labels':
            kwargs['export_labels'] = True
        elif key == '--labels-only':
            kwargs['emit'] = False
        elif key == '--foreign-labels':
            kwargs['foreign_label_map'] = read_label_json(value)
        elif key == '--foreign-prefix':
            kwargs['foreign_prefix'] = value
        elif key == '--host-data-offsets':
            kwargs['host_data_offsets'] = read_host_data_offsets(value)
        elif key == '--ds-starts':
            kwargs['ds_starts'] = read_ds_starts(value)
        elif key == '--records':
            from lib.record_layout import read_layouts
            kwargs['record_layouts'] = read_layouts(value)
    return kwargs


def inprocess_runners(project):
    """``(run_batch, nasm_batch, close)`` for the in-process ``python -m main`` path.

    The same sequence, with each worker step run in this process instead of as
    a ``python -m main --worker`` process; each binary keeps its analysis for
    its later steps (:class:`main.worker.BinaryRun`) until *close()*.  A
    failure raises (the CLI turns the pipeline's own errors into an exit
    status).
    """
    from .worker import BinaryRun, Project

    p = Project(project)
    runs = {}

    def run_batch(items):
        from .aztec import SourceBuildError
        emitted, failed = {}, []
        for name, flags in items:
            try:
                files = runs.setdefault(name, BinaryRun(p, name)).step(flags)
            except SourceBuildError as exc:
                print(str(exc))
                failed.append(name)
                files = exc.files
            if files is not None:
                emitted[name] = files
        return failed, emitted

    def nasm_batch(items):
        return [name for name, rel in items
                if nasm_binary(p.out_dir, name, rel) != 0]

    def close():
        for run in runs.values():
            run.close()
        runs.clear()

    return run_batch, nasm_batch, close
