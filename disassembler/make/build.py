"""``make build`` / ``make rebuild`` — assembly generation and NASM builds.

The generation order itself lives in :mod:`main.build`, so ``make build`` and
``python -m main`` cannot drift apart.  What ``make`` adds is the process
model: every binary is generated by its own ``python -m main --worker``
process, kept for the whole build so its later steps reuse its analysis, and
both that step and the NASM step run on a thread pool.
"""

import json
import os
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed

from main.projects import discover_binaries
from main.build import build_project, nasm_binary
from lib import progress
from lib.cachedirs import src_dir
from lib.link import LinkError
from lib.report import clear_project_stats
from lib.sidecar.errors import SidecarError

from main.clean import clear_build_out
from lib import progress

from .common import APPS, JOBS, PROJECT, Workers, _extra_flags, _verbose
from .prebuild import _ensure_prebuild


def _stats_enabled():
    return '--stats' in _extra_flags()


def _generate(workers):
    """A ``run_batch``: each binary's step on its worker, on a thread pool."""
    def run(items):
        failed, emitted = [], {}
        if _verbose():
            progress.log(f'batch: {len(items)} binar'
                         f'{"y" if len(items) == 1 else "ies"} -> '
                         f'{", ".join(name for name, _ in items)}')
        with ThreadPoolExecutor(max_workers=JOBS) as ex:
            futures = {ex.submit(workers.run, name, flags): name
                       for name, flags in items}
            for f in as_completed(futures):
                status, files = f.result()
                if status != 0:
                    print(f'  FAILED: {futures[f]}')
                    failed.append(futures[f])
                    # A failed consumer poisons the project; stop the batch.
                    ex.shutdown(wait=False, cancel_futures=True)
                    break
                if files is not None:
                    emitted[futures[f]] = files
        return failed, emitted
    return run


def _assemble(out_dir):
    """A ``nasm_batch``: assemble the given binaries on a thread pool."""
    def run(items):
        failed = []
        if _verbose():
            progress.log(f'nasm batch: {len(items)} binar'
                         f'{"y" if len(items) == 1 else "ies"} -> '
                         f'{", ".join(name for name, _ in items)}')
        with ThreadPoolExecutor(max_workers=JOBS) as ex:
            futures = {ex.submit(nasm_binary, out_dir, name, rel): name
                       for name, rel in items}
            for f in as_completed(futures):
                if f.result() != 0:
                    failed.append(futures[f])
        return failed
    return run


def asm_app(app):
    out_dir = src_dir(app, PROJECT)
    try:
        with Workers(app) as workers:
            failed = build_project(app, _generate(workers), _assemble(out_dir),
                                   overlap=True)
    except SidecarError as exc:
        print(f'{app}: sidecar configuration error: {exc}')
        sys.exit(1)
    except LinkError as exc:
        print(f'{app}: link error: {exc}')
        sys.exit(1)
    if failed:
        print(f'{app}: {len(set(failed))} binary(ies) failed to build')
        workers.print_errors()
        sys.exit(1)
    print(f'{app}: build OK')


def _prepare(app, *, prebuild=True):
    """What every build does first: drop the built binaries, make sure prebuild
    exists.  ``src_<app>/`` itself is left alone until the build has laid out
    every file (:func:`main.build._sync`)."""
    if _verbose():
        progress.log(f'{app} | prepare: clearing build_out')
    clear_build_out(app)
    if prebuild:
        _ensure_prebuild(app)
    if _stats_enabled():
        clear_project_stats(app)
    if _verbose():
        progress.log(f'{app} | prepare: done')


def cmd_build_binary(app, binary):
    app_dir = os.path.join(APPS, app)
    out_dir = src_dir(app, PROJECT)
    bins = discover_binaries(app_dir)
    if binary not in bins:
        print(f'Unknown binary "{binary}" in {app}')
        print(f'Known: {", ".join(sorted(bins))}')
        sys.exit(1)

    _prepare(app)
    if _verbose():
        progress.log(f'{app}/{binary} | build start')
    with Workers(app) as workers:
        failed = build_project(app, _generate(workers), _assemble(out_dir),
                               only=binary)
    if failed:
        workers.print_errors()
        sys.exit(1)
    print(f'build {app}/{binary} -> {bins[binary][0]}  [OK]')


def _routine_donors(app, routine):
    """The binaries whose span sidecar contains *routine*."""
    from lib.cachedirs import spans_dir
    out = []
    for name in sorted(discover_binaries(os.path.join(APPS, app))):
        path = os.path.join(spans_dir(app), f'{name}_aztec_spans.json')
        try:
            with open(path) as f:
                spans = json.load(f)
        except (OSError, ValueError):
            continue
        if routine in spans:
            out.append(name)
    return out


def _rebuild_targets(app, bins, binary, only):
    """``(binaries, routine)`` to gate for a rebuild selector.

    The selector is a real binary, or — when no routine follows it — the
    routine itself.  A routine is gated against every binary whose span
    sidecar contains it; that is how a routine in ``shared/`` reaches all its
    donors without ``shared/`` pretending to be a binary.
    """
    if binary is None:
        if only is not None:
            raise SystemExit(
                'a routine needs its binary: make rebuild PROJECT BIN ROUTINE')
        return sorted(bins), None
    if binary in bins:
        return [binary], only
    if only is not None:
        print(f'Unknown binary "{binary}" in {app}')
        if binary == 'shared':
            print('shared/ is a source folder, not a binary; pass the '
                  f'routine instead: make rebuild {app} {only}')
        else:
            print(f'Known: {", ".join(sorted(bins))}')
        raise SystemExit(1)
    if binary == 'shared':
        print('shared/ is a source folder, not a binary; pass the routine '
              f'instead: make rebuild {app} ROUTINE')
        raise SystemExit(1)
    targets = _routine_donors(app, binary)
    if not targets:
        raise SystemExit(
            f'error: {binary}: no binary contains that routine')
    return targets, binary


def _rebuild_project(app, binary=None, only=None):
    """Recompile every ``.c`` (gated against the original) then NASM-assemble.

    *only* limits the C gate to one routine's source; the binary still
    assembles, so the check covers both "the C reproduces its bytes" and
    "the fragment assembles in place".

    ``BIN`` is a real binary when a routine follows it.  With only two
    arguments the selector is the routine, gated against every binary whose
    span sidecar contains it (including a routine that lives in ``shared/``).
    """
    from .elf import resplice_c
    app_dir = os.path.join(APPS, app)
    out_dir = src_dir(app, PROJECT)
    bins = discover_binaries(app_dir)
    targets, routine = _rebuild_targets(app, bins, binary, only)
    for name in targets:
        if _verbose():
            progress.log(f'{app}/{name} | resplicing C routines')
        resplice_c(app, name, check_only=True, only=routine)
    for name in targets:
        if _verbose():
            progress.log(f'{app}/{name} | nasm')
        if nasm_binary(out_dir, name, bins[name][0]) != 0:
            print(f'rebuild {app}/{name} -> {bins[name][0]}  [FAILED]')
            sys.exit(1)
        if _verbose():
            print(f'rebuild {app}/{name} -> {bins[name][0]}  [OK]')
    print(f'rebuild {app}: {len(targets)} binar{"y" if len(targets) == 1 else "ies"} OK')


def cmd_rebuild(app=None, binary=None, all_projects=(), only=None):
    """``make rebuild [PROJECT [BIN [ROUTINE]]]``."""
    for project in ([app] if app else all_projects):
        _rebuild_project(project, binary, only)


def _build_projects(targets, all_projects, *, prebuild=True):
    for project in targets:
        if project not in all_projects:
            print(f'Unknown project: {project}')
            print(f'Known: {", ".join(all_projects)}')
            sys.exit(1)
    for project in targets:
        _prepare(project, prebuild=prebuild)
        asm_app(project)
